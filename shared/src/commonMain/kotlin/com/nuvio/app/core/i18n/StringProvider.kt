/**
 * Resolves a [StringKey] to a localized string. `args` are positional format arguments for
 * keys that contain placeholders (e.g. `compose_player_episode_code_full`). Return `null`
 * to let the caller use its English fallback.
 */
fun interface StringProvider {
    fun get(key: StringKey, vararg args: Any?): String?
}

/**
 * Process-wide holder for the active [StringProvider]. The phone app installs a
 * Compose-Resources-backed provider at startup; tvOS leaves it null and uses fallbacks.
 */
object LocalizedStrings {
    @Volatile
    var provider: StringProvider? = null
}

/**
 * Resolve [key] via the installed provider, or return [fallback] (the English default) when
 * no provider is installed or the provider has no value for the key.
 */
fun resourceString(
    fallback: String,
    key: StringKey,
    vararg args: Any?,
): String = LocalizedStrings.provider?.get(key, *args) ?: fallback
