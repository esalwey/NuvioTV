package com.nuvio.app.core.account

/*
 * Single source of truth for every persisted store that a full account sign-out must erase.
 *
 * Three hand-maintained lists used to own this knowledge independently and drifted apart:
 *  - `core.bootstrap.TvOsProviderInstaller`'s `TvOsAccountDataCleaner` (tvOS, NSUserDefaults),
 *  - composeApp's `PlatformLocalAccountDataCleaner.ios` (iOS, NSUserDefaults),
 *  - composeApp's `PlatformLocalAccountDataCleaner.android` (SharedPreferences file names),
 *  - `core.storage.AppleFilePayloadStores` (the file-backed PayloadFileStore subdirectories).
 *
 * Every entry below is TRANSCRIBED from the real key constants in each store's `actual` — never
 * inferred from a naming convention — and this list is a superset of the union of those four.
 *
 * ## Why this is a static list and not self-registration
 * A store that registered itself from its own `init {}` block would only register once something
 * touched the object: Kotlin `object` initializers are lazy, so a store nobody read during the
 * session would silently never register and would silently never be wiped. That is the exact
 * failure mode this registry exists to remove, so DO NOT add `init {}` hooks or a mutable
 * registration API here. Adding a store means adding a line to [AccountDataStores.all].
 *
 * ## Purity
 * This file is data only: no platform imports, no `expect`/`actual`, no NSUserDefaults or
 * SharedPreferences types. Each platform cleaner consumes the projections at the bottom.
 */

/**
 * How an Apple (iOS/tvOS) `NSUserDefaults` key is actually spelled at the call site. Getting this
 * wrong means the wipe silently misses the data, so each variant mirrors one concrete call shape
 * observed in the storage `actual`s.
 */
sealed interface AppleKeySpec {
    /** Raw unscoped key: `defaults.stringForKey("profile_payload")`. */
    data class Plain(val key: String) : AppleKeySpec

    /** `ProfileScopedKey.of(base)` → `"<base>_<activeProfileId>"`; wipe for every profile slot. */
    data class ProfileScoped(val base: String) : AppleKeySpec

    /** Key built inline as `"<prefix><profileId>"`; wipe for every profile slot. */
    data class ProfileIndexed(val prefix: String) : AppleKeySpec

    /**
     * Key embeds runtime data (a content-id hash, a scraper/manifest URL, a debrid provider id),
     * so it cannot be enumerated: wipe by scanning `defaults.dictionaryRepresentation()` and
     * removing every key that starts with [prefix]. [prefix] is the longest literal prefix that
     * is still safe to match on.
     */
    data class DynamicPrefix(val prefix: String) : AppleKeySpec

    /** A `core.storage.PayloadFileStore` subdirectory of Application Support. */
    data class FileStore(val subdirectory: String) : AppleKeySpec
}

/**
 * One persisted store.
 *
 * @param name the storage object that owns the data (for humans and for grep).
 * @param androidPreferences the `preferencesName` its `.android.kt` actual passes to
 *   `getSharedPreferences`, or null when the store has no Android backing at all.
 * @param appleKeys every key/prefix/subdirectory its Apple actual writes.
 */
