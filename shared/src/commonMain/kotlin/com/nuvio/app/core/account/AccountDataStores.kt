    /** SharedPreferences file names for the Android cleaner's whole-file `clear()`. */
    fun androidPreferenceNames(): List<String> =
        all.mapNotNull { it.androidPreferences }.distinct()

    /** Unscoped keys — remove verbatim. */
    fun applePlainKeys(): List<String> =
        appleKeys().filterIsInstance<AppleKeySpec.Plain>().map { it.key }.distinct()

    /** Base keys — remove `"<base>_<profileId>"` for every profile slot (1..MAX_PROFILES). */
    fun appleProfileScopedBases(): List<String> =
        appleKeys().filterIsInstance<AppleKeySpec.ProfileScoped>().map { it.base }.distinct()

    /** Prefixes — remove `"<prefix><profileId>"` for every profile slot (1..MAX_PROFILES). */
    fun appleProfileIndexedPrefixes(): List<String> =
        appleKeys().filterIsInstance<AppleKeySpec.ProfileIndexed>().map { it.prefix }.distinct()

    /** Prefixes to match while scanning `NSUserDefaults.dictionaryRepresentation()`. */
    fun appleDynamicPrefixes(): List<String> =
        appleKeys().filterIsInstance<AppleKeySpec.DynamicPrefix>().map { it.prefix }.distinct()

    /** `PayloadFileStore` subdirectories to delete wholesale. */
    fun appleFileStoreSubdirectories(): List<String> =
        appleKeys().filterIsInstance<AppleKeySpec.FileStore>().map { it.subdirectory }.distinct()

    private fun appleKeys(): List<AppleKeySpec> = all.flatMap { store -> store.appleKeys }
}
