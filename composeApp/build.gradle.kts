abstract class GenerateRuntimeConfigsTask : DefaultTask() {
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @get:Optional
    @get:InputFile
    abstract val localPropertiesFile: RegularFileProperty

    @get:Input
    abstract val appVersionName: Property<String>

    @get:Input
    abstract val appVersionCode: Property<Int>

    @get:Input
    abstract val supabaseUrl: Property<String>

    @get:Input
    abstract val supabaseAnonKey: Property<String>

    @get:Input
    abstract val supabaseFallbackUrl: Property<String>

    @get:Input
    abstract val sentryDsn: Property<String>

    @get:Input
    abstract val sentryEnvironment: Property<String>

    @TaskAction
    fun generate() {
        val props = Properties()
        localPropertiesFile.asFile.orNull?.takeIf { it.exists() }?.inputStream()?.use { props.load(it) }

        val outDir = outputDir.get().asFile
        // NOTE: SupabaseConfig + SyncBackendBootstrapConfig (core/network) and
        // AppVersionConfig + AppBuildConfig (core/build) are generated by :shared's
        // generateSharedRuntimeConfigs task instead, and reach composeApp transitively via
        // implementation(projects.shared). They must NOT be generated here too, or the FQNs
        // would be duplicated across modules. Only feature configs are generated below.
        outDir.resolve("com/nuvio/app/core/diagnostics").apply {
            mkdirs()
            resolve("SentryConfig.kt").writeText(
                """
                |package com.nuvio.app.core.diagnostics
                |
                |object SentryConfig {
                |    const val DSN = "${sentryDsn.get()}"
                |    const val ENVIRONMENT = "${sentryEnvironment.get()}"
                |}
                """.trimMargin()
            )
        }

        outDir.resolve("com/nuvio/app/features/tmdb/TmdbConfig.kt").delete()
        // TraktConfig (com.nuvio.app.features.trakt.TraktConfig) is generated by :shared's
        // generateSharedRuntimeConfigs task instead (reaches composeApp transitively via
        // implementation(projects.shared)). Must NOT be generated here too, or the FQN would be
        // duplicated across modules. Delete any stale composeApp-generated copy.
        outDir.resolve("com/nuvio/app/features/trakt/TraktConfig.kt").delete()

        // SimklConfig (com.nuvio.app.features.simkl.SimklConfig) is generated by :shared's
        // generateSharedRuntimeConfigs task instead (the whole features/simkl package moved to
        // :shared). It reaches composeApp transitively via implementation(projects.shared). Must
        // NOT be generated here too, or the FQN would be duplicated across modules — and upstream
        // still generates it in composeApp, so a catch-up merge can reintroduce a stale copy.
        outDir.resolve("com/nuvio/app/features/simkl/SimklConfig.kt").delete()

        // IntroDbConfig now generated into :shared (consumed by SkipIntroApi/SkipIntroRepository,
        // which moved to :shared). Delete any stale composeApp-generated copy to avoid dup FQN.
        outDir.resolve("com/nuvio/app/features/player/skip/IntroDbConfig.kt").delete()

        // ImdbEpisodeRatingsConfig (com.nuvio.app.features.details.ImdbEpisodeRatingsConfig) is now
        // generated by :shared's generateSharedRuntimeConfigs task instead (consumed by SeriesGraphApi/
        // ImdbEpisodeRatingsRepository, which moved to :shared). It reaches composeApp transitively via
        // implementation(projects.shared). Must NOT be generated here too, or the FQN would be
        // duplicated across modules. Delete any stale composeApp-generated copy.
        outDir.resolve("com/nuvio/app/features/details/ImdbEpisodeRatingsConfig.kt").delete()

        // PremiumizeConfig (com.nuvio.app.features.debrid.PremiumizeConfig) is generated by :shared's
        // generateSharedRuntimeConfigs task instead (reaches composeApp transitively via
        // implementation(projects.shared)). Must NOT be generated here too, or the FQN would be
        // duplicated across modules. Delete any stale composeApp-generated copy.
        outDir.resolve("com/nuvio/app/features/debrid/PremiumizeConfig.kt").delete()

        // core/build AppVersionConfig + AppBuildConfig are generated by :shared (see note above).

        outDir.resolve("com/nuvio/app/features/settings").apply {
            mkdirs()
            resolve("CommunityConfig.kt").writeText(
                """
                |package com.nuvio.app.features.settings
                |
                |object CommunityConfig {
                |    const val CONTRIBUTIONS_URL = "${props.getProperty("CONTRIBUTIONS_URL", "")}" 
                |    const val DONATIONS_BASE_URL = "${props.getProperty("DONATIONS_BASE_URL", "")}" 
                |    const val DONATIONS_DONATE_URL = "${props.getProperty("DONATIONS_DONATE_URL", "")}" 
                |}
                """.trimMargin()
            )
        }
    }
}

fun readXcconfigValue(file: File, key: String): String? {
    if (!file.exists()) return null
    return file.readLines()
        .asSequence()
        .map(String::trim)
        .filter { it.isNotEmpty() && !it.startsWith("#") && it.contains('=') }
        .map { line ->
            val separatorIndex = line.indexOf('=')
            line.substring(0, separatorIndex).trim() to line.substring(separatorIndex + 1).trim()
        }
        .firstOrNull { (entryKey, _) -> entryKey == key }
        ?.second
}

